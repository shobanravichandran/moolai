"""Backtest reviewer suggestions on real merged PRs: would we have named someone who actually reviewed it?

Usage: python -m scripts.backtest_reviewers [--limit 300] [--since 2026-06-01] [--query suggest_reviewers ...]
                                            [--out docs/backtest.md]

For each merged PR in scope (tagged sig-auth / sig-network / sig-node, created after --since, with at least
one human reviewer other than the author), suggestions are computed **as of the PR's creation time**: only PRs
merged before then count, so nothing about the PR's own review leaks in. Ground truth = the people who
reviewed it.

Methods compared:
- each --query (Moolai's file/component-aware scoring variants)
- team-top: the busiest reviewers of PRs with the same SIG labels (what you'd guess from the SIG alone)
- random-pool: a random person who reviewed anything in the same components before (roughly Prow's
  blunderbuss, which picks randomly from OWNERS). Its hit@k and MRR are computed exactly, not sampled.
"""

import argparse
import statistics
import time
from datetime import UTC, date, datetime
from math import comb
from pathlib import Path

from moolai.db import run

TEAMS = ["sig-auth", "sig-network", "sig-node"]
WINDOW_S = 365 * 86400
K = 10


def ranks_metrics(ranked: list[str], truth: set[str]) -> dict:
    first = next((i + 1 for i, login in enumerate(ranked[:K]) if login in truth), None)
    return {
        "hit1": float(first == 1),
        "hit3": float(first is not None and first <= 3),
        "mrr": 1.0 / first if first else 0.0,
        "covered": float(bool(ranked)),
    }


def random_pool_metrics(pool: set[str], truth: set[str]) -> dict:
    """Exact expected hit@1, hit@3 and MRR@K when picking a uniformly random order of the pool."""
    n, g = len(pool), len(pool & truth)
    if n == 0 or g == 0:
        return {"hit1": 0.0, "hit3": 0.0, "mrr": 0.0, "covered": float(n > 0)}

    def p_hit(k: int) -> float:
        return 1.0 - comb(n - g, min(k, n)) / comb(n, min(k, n))

    # P(first relevant at rank r) = C(n-r, g-1) / C(n, g)
    mrr = sum(comb(n - r, g - 1) / comb(n, g) / r for r in range(1, min(K, n) + 1))
    return {"hit1": p_hit(1), "hit3": p_hit(3), "mrr": mrr, "covered": 1.0}


def backtest(limit: int, since: date, queries: list[str]) -> dict:
    since_s = int(datetime.combine(since, datetime.min.time(), tzinfo=UTC).timestamp())
    sample = run("backtest_sample", {"teams": TEAMS, "since": since_s, "limit": limit}, read_only=True)
    methods = [*queries, *(f"{q}+fallback" for q in queries), "team-top", "random-pool"]
    scores: dict[str, list[dict]] = {m: [] for m in methods}
    ms: dict[str, list[float]] = {m: [] for m in methods}
    for pr in sample:
        truth = {r["login"] for r in run("pr_actual_reviewers", {"pr_id": pr["id"]}, read_only=True)}
        ctx = run("pr_context", {"pr_id": pr["id"]}, read_only=True)[0]
        exclude = ctx["author"]
        params = {"pr_id": pr["id"], "as_of": pr["created_at"], "window_s": WINDOW_S}
        t = time.perf_counter()
        team = run(
            "baseline_team_reviewers",
            {
                "teams": pr["teams"],
                "as_of": pr["created_at"],
                "window_s": WINDOW_S,
                "exclude": exclude,
                "k": K,
            },
            read_only=True,
        )
        team_ranked = [r["login"] for r in team]
        ms["team-top"].append((time.perf_counter() - t) * 1000)
        scores["team-top"].append(ranks_metrics(team_ranked, truth))
        for q in queries:
            t = time.perf_counter()
            ranked = [r["login"] for r in run(q, {**params, "k": K}, read_only=True)]
            ms[q].append((time.perf_counter() - t) * 1000)
            scores[q].append(ranks_metrics(ranked, truth))
            # What the API does: top up with the SIG's busiest reviewers when file history runs out.
            filled = ranked + [login for login in team_ranked if login not in ranked]
            ms[f"{q}+fallback"].append(ms[q][-1] + ms["team-top"][-1])
            scores[f"{q}+fallback"].append(ranks_metrics(filled, truth))
        t = time.perf_counter()
        pool = run("baseline_component_pool", {**params, "exclude": exclude}, read_only=True)
        ms["random-pool"].append((time.perf_counter() - t) * 1000)
        scores["random-pool"].append(random_pool_metrics({r["login"] for r in pool}, truth))
    summary = {
        m: {
            **{k: statistics.mean(s[k] for s in scores[m]) for k in ("hit1", "hit3", "mrr", "covered")},
            "p50_ms": statistics.median(ms[m]),
        }
        for m in methods
        if scores[m]
    }
    return {"n": len(sample), "since": since.isoformat(), "summary": summary}


def markdown(result: dict) -> str:
    lines = [
        "# Reviewer suggestion backtest",
        "",
        f"Generated by `python -m scripts.backtest_reviewers` on {date.today().isoformat()}.",
        "",
        f"**{result['n']} merged PRs** labelled {', '.join(TEAMS)} and created since {result['since']}.",
        "For each PR, suggestions use only PRs merged **before it was opened**. A hit means a suggestion",
        "actually reviewed it (GitHub review, `/lgtm` or `/approve`; the author and bots excluded).",
        "",
        "| Method | hit@1 | hit@3 | MRR@10 | has suggestions | p50 query ms |",
        "|---|---|---|---|---|---|",
    ]
    for m, s in result["summary"].items():
        cells = [f"`{m}`", f"{s['hit1']:.1%}", f"{s['hit3']:.1%}", f"{s['mrr']:.3f}", f"{s['covered']:.0%}"]
        lines.append("| " + " | ".join([*cells, f"{s['p50_ms']:.0f}"]) + " |")
    lines += [
        "",
        "- `suggest_reviewers`: Moolai's scoring (queries/suggest_reviewers.cypher).",
        "- `+fallback`: tops the list up with `team-top` when file history runs out (what the API returns).",
        "- `team-top`: the most active reviewers of PRs with the same SIG labels (no file knowledge).",
        "- `random-pool`: a uniformly random past reviewer from the same components, roughly what Prow's",
        "  blunderbuss does with OWNERS. Expected values, computed exactly.",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--limit", type=int, default=300)
    p.add_argument("--since", type=date.fromisoformat, default=date(2026, 6, 1))
    p.add_argument("--query", action="append", help="reviewer query name(s) to evaluate")
    p.add_argument("--out", type=Path)
    a = p.parse_args()
    res = backtest(a.limit, a.since, a.query or ["suggest_reviewers"])
    md = markdown(res)
    print(md)
    if a.out:
        a.out.parent.mkdir(parents=True, exist_ok=True)
        a.out.write_text(md, encoding="utf-8", newline="\n")
